export const getProduct = (id: string) => PRODUCTS.find((p) => p.id === id);

export const searchProducts = (q: string) => {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return PRODUCTS.filter((p) =>
    [p.name, p.category, p.description, ...p.tags, ...p.types]
      .join(" ")
      .toLowerCase()
      .includes(s),
  );
};
